import {test,expect} from "@playwright/test";

test("overview and sidebar support the analysis workflow on desktop and mobile",async({page})=>{
  await page.goto("/");
  const nav=page.getByRole("navigation",{name:"Workspace navigation"});
  const home=page.getByRole("region",{name:"Workspace overview"});
  await expect(home).toBeVisible();
  await expect(nav.getByRole("button",{name:"Overview",exact:true})).toHaveAttribute("aria-current","page");
  const desktopToggle=page.getByRole("button",{name:"Toggle navigation"});
  await desktopToggle.click();await expect(desktopToggle).toHaveAttribute("aria-expanded","false");
  await expect(nav.getByRole("button",{name:"Analysis",exact:true})).toBeVisible();
  await desktopToggle.click();await expect(desktopToggle).toHaveAttribute("aria-expanded","true");
  await home.getByRole("button",{name:"New analysis",exact:false}).click();
  await expect(page.getByRole("heading",{name:"Configure analysis"})).toBeVisible();
  await page.getByRole("button",{name:"Load synthetic demo"}).click();
  await page.getByRole("group",{name:"Analysis mode"}).getByRole("button",{name:"Research",exact:true}).click();
  await page.getByLabel("Experimental method",{exact:true}).selectOption("bm25");
  await page.getByRole("button",{name:"Run impact analysis"}).click();
  await expect(page.getByTestId("report-view")).toBeVisible({timeout:30_000});
  const id=new URL(page.url()).searchParams.get("analysis");expect(id).toBeTruthy();
  await page.getByTestId("impact-details").first().click();
  await expect(page.getByRole("heading",{name:"Why this file or function?"}).first()).toBeVisible();
  await page.screenshot({path:test.info().outputPath("analysis-desktop.png"),fullPage:false});
  await nav.getByRole("button",{name:"Overview",exact:true}).click();
  await expect(home.getByRole("button",{name:"Open current analysis"})).toBeVisible();
  await page.screenshot({path:test.info().outputPath("overview-desktop.png"),fullPage:false});
  await page.reload();await expect(home).toBeVisible();
  await home.getByRole("button",{name:"Open current analysis"}).click();
  await expect(page.getByTestId("report-view")).toBeVisible();
  await page.setViewportSize({width:390,height:844});
  const toggle=page.getByRole("button",{name:"Toggle navigation"});
  await toggle.click();await expect(nav).toBeVisible();
  await page.keyboard.press("Escape");await expect(toggle).toBeFocused();
  await expect(nav).not.toBeVisible();
  await toggle.click();await page.getByRole("button",{name:"Close sidebar",exact:true}).click();
  await expect(nav).not.toBeVisible();await expect(toggle).toBeFocused();
  await toggle.click();await nav.getByRole("button",{name:"Overview",exact:true}).click();
  await expect(nav).not.toBeVisible();await expect(home).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  await page.screenshot({path:test.info().outputPath("overview-mobile.png"),fullPage:true});
});
